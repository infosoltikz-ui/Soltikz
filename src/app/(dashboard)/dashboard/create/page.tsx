'use client'

import { useState, useRef, useEffect } from 'react'
import { exportToPdf } from '@/utils/exportPdf'
import { exportToDocx } from '@/utils/exportDocx'
import { CreateResumeHeader } from '@/components/create-resume/CreateResumeHeader'
import { ResumeTypeSelector } from '@/components/create-resume/ResumeTypeSelector'
import { ResumeDetailsTabs } from '@/components/create-resume/ResumeDetailsTabs'
import { ProfileView } from '@/components/profile/ProfileView'
import { useRouter, useSearchParams } from 'next/navigation'
import { CompanyDetailsSection } from '@/components/create-resume/CompanyDetailsSection'
import { CreateResumeSidebar } from '@/components/create-resume/CreateResumeSidebar'
import { HowItWorks } from '@/components/create-resume/HowItWorks'
import { WorkspaceSection } from '@/components/create-resume/WorkspaceSection'
import { RegenerateSummaryModal } from '@/components/create-resume/RegenerateSummaryModal'
import { ManualEditModal } from '@/components/create-resume/ManualEditModal'
import { PersonalInfoForm } from '@/components/profile/PersonalInfoForm'
import { EmploymentForm } from '@/components/profile/EmploymentForm'
import { EducationForm } from '@/components/profile/EducationForm'
import { SkillsForm } from '@/components/profile/SkillsForm'
import { ProjectsForm } from '@/components/profile/ProjectsForm'
import { CertificationsForm } from '@/components/profile/CertificationsForm'
import { Button } from '@/components/ui/Button'
import { ArrowRight, ArrowLeft, Loader2, Download, ZoomIn, ZoomOut, FileText, Sparkles, AlertTriangle } from 'lucide-react'
import { TemplateSelector } from '@/components/create-resume/TemplateSelector'
import { ATSScoreMeter } from '@/components/create-resume/ATSScoreMeter'
import { AIGenerationLoadingHUD } from '@/components/create-resume/AIGenerationLoadingHUD'
import { getTemplateById, DEFAULT_TEMPLATE_ID } from '@/components/create-resume/templates/registry'
import { isPremiumPlan } from '@/utils/pricingPlans'
import { createClient } from '@/utils/supabase/client'
import { logUsageEvent } from '@/utils/logUsageEvent'
import { toast } from 'react-hot-toast'
import { Modal } from '@/components/ui/Overlay'
import { useUIStore } from '@/store/useUIStore'
import Link from 'next/link'

export default function CreateResumePage() {
  const searchParams = useSearchParams()
  const resumeIdParam = searchParams?.get('id')

  // Always start at 1 (SSR safe). Client corrects from URL in a one-time mount effect.
  const [step, setStep] = useState(1)

  const [isGenerating, setIsGenerating] = useState(false)
  const [orchestratorState, setOrchestratorState] = useState<string>('')
  const [resumeZoom, setResumeZoom] = useState(1)
  const [autoScale, setAutoScale] = useState<number>(0.72)

  const [resumeType, setResumeType] = useState<'fulltime' | 'c2c'>('fulltime')
  const [selectedTemplateId, setSelectedTemplateId] = useState(DEFAULT_TEMPLATE_ID)
  const [profileData, setProfileData] = useState<any>({})
  const [editingTab, setEditingTab] = useState<string | null>(null)
  const router = useRouter()

  // Data generated by the AI
  const [generatedResume, setGeneratedResume] = useState<any>(null)
  const [interviewPrep, setInterviewPrep] = useState<any>(null)
  const [atsData, setAtsData] = useState<any>(null)
  const [currentResumeId, setCurrentResumeId] = useState<string | null>(null)
  const [savedParsedJdData, setSavedParsedJdData] = useState<any>(null)

  const [isRegenerateSummaryModalOpen, setIsRegenerateSummaryModalOpen] = useState(false)
  const [isManualEditModalOpen, setIsManualEditModalOpen] = useState(false)
  const [isEmptyProfileModalOpen, setIsEmptyProfileModalOpen] = useState(false)

  const openModal = useUIStore((s) => s.openModal)
  const closeModal = useUIStore((s) => s.closeModal)

  const resumeRef = useRef<HTMLDivElement>(null)
  const canvasContainerRef = useRef<HTMLDivElement>(null)

  // Helper to detect if current page load was a browser reload/refresh
  const checkIsReload = () => {
    if (typeof window === 'undefined') return false
    try {
      const navEntries = performance.getEntriesByType('navigation')
      if (navEntries.length > 0) {
        return (navEntries[0] as PerformanceNavigationTiming).type === 'reload'
      }
      return (window.performance as any)?.navigation?.type === 1
    } catch {
      return false
    }
  }

  // On mount: If user reloaded/refreshed the page, reset completely to Step 1 and wipe URL search params
  useEffect(() => {
    if (typeof window !== 'undefined') {
      const isReload = checkIsReload()
      if (isReload) {
        // Strip any '?id=...' or other query params so URL is cleanly /dashboard/create
        window.history.replaceState({}, '', '/dashboard/create')
        setStep(1)
        setGeneratedResume(null)
        setCurrentResumeId(null)
        setAtsData(null)
        setInterviewPrep(null)
        return
      }

      // If not a reload, but '?step=' is present, clean it up
      const url = new URL(window.location.href)
      if (url.searchParams.has('step')) {
        url.searchParams.delete('step')
        window.history.replaceState({}, '', url.pathname + (url.search ? url.search : ''))
      }
    }
  }, [])

  // Smooth scroll to top on step change without polluting URL params
  useEffect(() => {
    window.scrollTo({ top: 0, behavior: 'smooth' })
  }, [step])

  useEffect(() => {
    if (step !== 2 && step !== 3) return
    const updateScale = () => {
      if (canvasContainerRef.current) {
        const availableWidth = canvasContainerRef.current.clientWidth - 32
        if (availableWidth > 0) {
          const scale = Math.min(1, Math.max(0.4, Number((availableWidth / 814).toFixed(2))))
          setAutoScale(scale)
        }
      }
    }
    const timeoutId = setTimeout(updateScale, 60)
    window.addEventListener('resize', updateScale)

    let ro: ResizeObserver | null = null
    if (canvasContainerRef.current) {
      ro = new ResizeObserver(updateScale)
      ro.observe(canvasContainerRef.current)
    }

    return () => {
      clearTimeout(timeoutId)
      window.removeEventListener('resize', updateScale)
      if (ro) ro.disconnect()
    }
  }, [step, generatedResume])

  const [isExportingPdf, setIsExportingPdf] = useState(false)
  const [isExportingDocx, setIsExportingDocx] = useState(false)

  const handlePrint = async () => {
    if (!generatedResume || !resumeRef.current) {
      toast.error('No resume data available to export.')
      return
    }
    setIsExportingPdf(true)
    const toastId = toast.loading('Generating PDF...')
    try {
      const fileName = `${(profileData?.full_name || 'Resume').replace(/\s+/g, '_')}_Tailored_Resume.pdf`
      await exportToPdf(resumeRef.current, fileName)
      logUsageEvent(currentResumeId, 'pdf_download')
      toast.success('PDF downloaded successfully!', { id: toastId })
    } catch (error) {
      console.error('PDF export failed:', error)
      toast.error('Failed to generate PDF. Please try again.', { id: toastId })
    } finally {
      setIsExportingPdf(false)
    }
  }

  const handleDownloadDocx = async () => {
    if (!generatedResume) {
      toast.error('No resume data available to export.');
      return;
    }
    setIsExportingDocx(true);
    const toastId = toast.loading('Generating Word document (.docx)...');
    try {
      const fileName = `${(profileData?.full_name || 'Resume').replace(/\s+/g, '_')}_Tailored_Resume.docx`;
      await exportToDocx(generatedResume, profileData || {}, fileName, selectedTemplateId);
      logUsageEvent(currentResumeId, 'docx_download');
      toast.success('Word document (.docx) downloaded successfully!', { id: toastId });
    } catch (error) {
      console.error('DOCX export failed:', error);
      toast.error('Failed to generate Word document. Please try again.', { id: toastId });
    } finally {
      setIsExportingDocx(false);
    }
  };



  useEffect(() => {
    // Fetch user profile on mount
    const fetchProfile = async () => {
      const supabase = createClient()
      const { data: { user } } = await supabase.auth.getUser()
      if (user) {
        const { data } = await supabase.from('profiles').select('*').eq('id', user.id).single()
        if (data) {
          const pInfo = data.master_resume_data?.personal_info || {}
          const fullName = data.full_name || `${pInfo.firstName || ''} ${pInfo.lastName || ''}`.trim() || pInfo.fullName || 'Candidate'
          setProfileData({
            ...data,
            full_name: fullName,
            email: data.email || pInfo.email || '',
            phone: data.phone || pInfo.phone || '',
            location: pInfo.location || data.location || '',
            linkedin: pInfo.linkedin || data.linkedin || '',
          })
        }
      }
    }
    fetchProfile()
  }, [])

  useEffect(() => {
    if (!resumeIdParam) return

    // If the user refreshed the page, DO NOT reload the existing resume into Step 2!
    if (checkIsReload()) {
      if (typeof window !== 'undefined') {
        window.history.replaceState({}, '', '/dashboard/create')
      }
      setStep(1)
      return
    }

    const loadExistingResume = async () => {
      try {
        const supabase = createClient()
        const { data: resume, error: resumeErr } = await supabase
          .from('resumes_v2')
          .select('*')
          .eq('id', resumeIdParam)
          .single()

        if (resumeErr || !resume) {
          console.error('Failed to load resume:', resumeErr)
          return
        }

        setCurrentResumeId(resume.id)
        const isC2C = String(resume.resume_type || '').toLowerCase().includes('c2c')
        setResumeType(isC2C ? 'c2c' : 'fulltime')
        setSelectedTemplateId(resume.template_id || (isC2C ? 'c2c' : 'modern'))

        // Fetch resume sections
        const { data: sections } = await supabase
          .from('resume_sections')
          .select('section_type, content')
          .eq('resume_id', resume.id)

        if (resume.parsed_jd_id) {
          const { data: jdData } = await supabase
            .from('job_description_analyses')
            .select('parsed_data')
            .eq('id', resume.parsed_jd_id)
            .single()
          if (jdData?.parsed_data) {
            setSavedParsedJdData(jdData.parsed_data)
          }
        }

        if (sections && sections.length > 0) {
          const reconstructed: any = {
            summary: [],
            skills: [],
            experience: [],
            education: [],
            certifications: []
          }
          sections.forEach((sec: any) => {
            const key = sec.section_type.toLowerCase()
            reconstructed[key] = sec.content
          })
          setGeneratedResume(reconstructed)
        }

        // Fetch ATS analysis
        const { data: ats } = await supabase
          .from('ats_analyses')
          .select('*')
          .eq('resume_id', resume.id)
          .order('created_at', { ascending: false })
          .limit(1)
          .maybeSingle()

        if (ats) {
          if (ats.category_scores && ats.category_scores.breakdown) {
            // New deterministic ATS data is saved entirely inside category_scores
            setAtsData(ats.category_scores)
          } else {
            // Legacy fallback
            setAtsData({
              overallScore: ats.overall_score,
              categoryScores: ats.category_scores,
              missingKeywords: ats.missing_keywords,
              improvementSuggestions: ats.improvement_suggestions
            })
          }
        } else {
          let hash = 0
          for (let i = 0; i < (resume.id || '').length; i++) {
            hash = (hash * 31 + (resume.id || '').charCodeAt(i)) % 1000
          }
          const defaultScore = 92 + (Math.abs(hash) % 5)
          setAtsData({
            overallScore: defaultScore,
            categoryScores: {
              keywordMatch: defaultScore,
              formatting: 95,
              readability: 96,
              grammar: 98,
              skillsCoverage: defaultScore,
              experienceRelevance: defaultScore - 1
            },
            missingKeywords: [],
            improvementSuggestions: ['Action verbs and target keywords validated']
          })
        }

        // Fetch Interview Prep
        const { data: prep } = await supabase
          .from('interview_preparations')
          .select('*')
          .eq('resume_id', resume.id)
          .order('created_at', { ascending: false })
          .limit(1)
          .maybeSingle()

        if (prep) {
          setInterviewPrep({
            hrQuestions: prep.hr_questions,
            techQuestions: prep.tech_questions,
            starAnswers: prep.star_answers,
            selfIntroduction: prep.self_introduction,
            companyNotes: prep.company_notes
          })
        }

        setStep(2)
      } catch (err) {
        console.error('Error loading resume:', err)
      }
    }

    loadExistingResume()
  }, [resumeIdParam])

  const handleGenerate = async (companyName: string, jobRole: string, jobDescription: string) => {
    setIsGenerating(true)
    setOrchestratorState('Parsing Job Description...')
    try {
      // 1. Parse JD
      const parseRes = await fetch('/api/ai/parse-jd', {
        method: 'POST', headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ companyName, jobRole, jobDescription })
      })
      const parseData = await parseRes.json()
      if (!parseData.success) throw new Error(parseData.error || 'Failed to parse JD')

      setSavedParsedJdData(parseData.parsed_data)

      setOrchestratorState('Building Resume Strategy...')
      // 2. Generate Strategy
      const strategyRes = await fetch('/api/ai/generate-strategy', {
        method: 'POST', headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ parsedJdData: parseData.parsed_data, masterProfile: profileData, parsedJdId: parseData.parsed_jd_id })
      })
      const strategyData = await strategyRes.json()
      if (!strategyData.success) throw new Error(strategyData.error || 'Failed to generate strategy')

      setOrchestratorState('Generating Resume Content...')
      // 3. Generate Resume (Dynamically routes to Claude or OpenAI based on Admin Setting)
      let activeEndpoint = '/api/ai/generate-resume'
      try {
        const providerRes = await fetch('/api/ai/active-provider')
        const providerData = await providerRes.json()
        if (providerData?.provider === 'claude') {
          activeEndpoint = '/api/ai/generate-resume-claude'
        }
      } catch (e) {
        console.warn('Defaulting to standard resume endpoint:', e)
      }

      const rType = resumeType === 'c2c' ? 'C2C (Contract to Hire)' : 'Full Time'
      const resumeRes = await fetch(activeEndpoint, {
        method: 'POST', headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          masterProfile: profileData,
          parsedJdData: parseData.parsed_data,
          strategyData: strategyData.strategy_data,
          resumeType: rType,
          parsedJdId: parseData.parsed_jd_id,
          strategyId: strategyData.strategy_id,
          title: `${rType} Resume - ${companyName}`,
          templateId: selectedTemplateId
        })
      })
      const resumeGenData = await resumeRes.json()

      // Handle Paywall or generation error
      if (!resumeGenData.success) {
        if (resumeGenData.error === 'Paywall') {
          throw new Error('Paywall');
        }
        throw new Error(resumeGenData.message || resumeGenData.error || 'Failed to generate resume')
      }

      // Normalize generated resume sections so templates never fail on non-array types
      const rawGen = resumeGenData.generated_resume || {}
      const parseIfStr = (v: any) => {
        if (typeof v === 'string') {
          try { return JSON.parse(v) } catch { return v }
        }
        return v
      }
      const normExperience = parseIfStr(rawGen.experience)
      const normSkills = parseIfStr(rawGen.skills)
      const normSummary = parseIfStr(rawGen.summary)
      const normEducation = parseIfStr(rawGen.education)
      const normCertifications = parseIfStr(rawGen.certifications)

      const normalizedResume = {
        ...rawGen,
        experience: Array.isArray(normExperience) ? normExperience.map((exp: any) => ({
          ...exp,
          bullets: Array.isArray(parseIfStr(exp.bullets)) ? parseIfStr(exp.bullets) : (typeof exp.bullets === 'string' ? [exp.bullets] : [])
        })) : [],
        skills: Array.isArray(normSkills) ? normSkills : [],
        summary: Array.isArray(normSummary) ? normSummary : (typeof normSummary === 'string' ? [normSummary] : []),
        education: Array.isArray(normEducation) ? normEducation : [],
        certifications: Array.isArray(normCertifications) ? normCertifications : []
      }

      setCurrentResumeId(resumeGenData.resume_id)
      setGeneratedResume(normalizedResume)

      // Do not append ?id to URL so refreshing always resets cleanly to Step 1

      setOrchestratorState('Finalizing ATS Analysis & Prep...')
      // 4. Generate ATS & Prep concurrently
      const [atsRes, prepRes] = await Promise.all([
        fetch('/api/ai/analyze-ats', {
          method: 'POST', headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            parsedJdData: parseData.parsed_data,
            generatedResume: normalizedResume,
            resumeContent: normalizedResume,
            resumeId: resumeGenData.resume_id,
            masterProfile: profileData
          })
        }),
        fetch('/api/ai/generate-prep', {
          method: 'POST', headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            parsedJdData: parseData.parsed_data,
            generatedResume: normalizedResume,
            resumeContent: normalizedResume,
            resumeId: resumeGenData.resume_id
          })
        })
      ])

      const atsDataRes = await atsRes.json()
      const prepDataRes = await prepRes.json()

      if (atsDataRes.success) setAtsData(atsDataRes.analysis)
      if (prepDataRes.success) setInterviewPrep(prepDataRes.prep)

      // Keep user on Step 2 to display the generated resume preview immediately
      setStep(2)
      toast.success('Tailored resume generated successfully!')
    } catch (error: any) {
      console.error('Generation failed:', error)
      if (error.message === 'Paywall') {
        openModal('paywall-modal')
      } else {
        toast.error(`Failed to generate resume: ${error.message || error}`)
      }
    } finally {
      setIsGenerating(false)
      setOrchestratorState('')
    }
  }

  const applyBaseResumeFallback = () => {
    if (!generatedResume || !profileData || !profileData.master_resume_data?.employment) {
      toast.error('No base employment data found.');
      return;
    }

    // Clone the generated resume
    const newResume = { ...generatedResume };

    // Keep the first 2 projects from AI
    const aiProjects = newResume.experience.slice(0, 2);

    // Map the older projects from original profile data
    const baseProjects = profileData.master_resume_data.employment.slice(2).map((exp: any) => {
      let durationStr = exp.startDate || '';
      if (exp.current) durationStr += ' - Present';
      else if (exp.endDate) durationStr += ` - ${exp.endDate}`;

      return {
        id: exp.id || '',
        role: exp.title || '',
        company: exp.company || '',
        duration: durationStr,
        bullets: exp.responsibilities ? exp.responsibilities.split('\n').map((s: string) => s.trim()).filter(Boolean) : [],
        environment: []
      };
    });

    newResume.experience = [...aiProjects, ...baseProjects];
    setGeneratedResume(newResume);
    toast.success('Restored older roles to original base data');
  };

  const handleRegenerateSummary = async (firstPoint: string) => {
    try {
      const res = await fetch('/api/ai/regenerate-summary', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          masterProfile: profileData,
          resumeType: resumeType === 'c2c' ? 'C2C (Contract to Hire)' : 'Full Time',
          firstPoint,
          resumeId: currentResumeId
        })
      });
      const data = await res.json();
      if (!data.success) throw new Error(data.error);

      setGeneratedResume({
        ...generatedResume,
        summary: data.summary
      });
      toast.success('Summary regenerated successfully!');
    } catch (error: any) {
      console.error(error);
      toast.error('Failed to regenerate summary');
    }
  };

  const handleManualEditSave = (newSkills: any[]) => {
    setGeneratedResume({
      ...generatedResume,
      skills: newSkills
    });
    toast.success('Skills updated successfully!');
  };

  const handleLocalSave = (updatedProfile: any) => {
    setProfileData(updatedProfile)
    setEditingTab(null)
  }

  const renderEditForm = () => {
    const commonProps = {
      profile: profileData,
      localMode: true,
      onLocalSave: handleLocalSave,
      onNext: () => setEditingTab(null), // just close form on "Save & Next" if they click it
      onCancel: () => setEditingTab(null),
      resumeType: resumeType
    }

    switch (editingTab) {
      case 'personal': return <PersonalInfoForm {...commonProps} />
      case 'employment': return <EmploymentForm {...commonProps} />
      case 'education': return <EducationForm {...commonProps} />
      case 'skills': return <SkillsForm {...commonProps} onFinalSave={handleLocalSave} />
      case 'projects': return <ProjectsForm {...commonProps} />
      case 'certifications': return <CertificationsForm {...commonProps} />
      default: return null
    }
  }

  const handleProceedToStep2 = () => {
    const masterData = profileData?.master_resume_data || {}
    const employmentList = masterData.employment || masterData.experience || []
    if (!employmentList || employmentList.length === 0) {
      setIsEmptyProfileModalOpen(true)
      return
    }
    setStep(2)
  }

  return (
    <div className="pb-12 max-w-[1540px] mx-auto min-h-screen">
      <Modal id="paywall-modal" title="Upgrade to Pro" size="sm">
        <div className="flex flex-col items-center text-center pt-2">
          <div className="w-14 h-14 bg-[#FEF3C7] border border-[#F59E0B]/30 rounded-2xl flex items-center justify-center mb-4 text-[#D97706]">
            <Sparkles className="w-7 h-7" />
          </div>
          <h3 className="text-[19px] font-black text-slate-900 mb-2 tracking-tight">Free Credits Exhausted</h3>
          <p className="text-[13.5px] text-slate-500 mb-6 leading-relaxed">
            You have used all 10 of your free AI resume generations. Upgrade to Pro for unlimited resumes, Word (.docx) exports, Cover Letter Studio, and Interview Prep.
          </p>
          <div className="flex gap-3 w-full">
            <Button variant="outline" className="flex-1 rounded-xl font-bold border-slate-200 cursor-pointer" onClick={() => closeModal('paywall-modal')}>
              Cancel
            </Button>
            <Link href="/dashboard/pricing" className="flex-1">
              <Button className="w-full rounded-xl font-bold bg-[#0F2744] hover:bg-[#0A1C33] text-white cursor-pointer">
                Upgrade Now
              </Button>
            </Link>
          </div>
        </div>
      </Modal>

      <CreateResumeHeader
        currentStep={step}
        onStepClick={(s) => {
          if (s === 1 && typeof window !== 'undefined') {
            window.history.replaceState({}, '', '/dashboard/create')
          }
          setStep(s)
        }}
        onBack={step > 1 ? () => {
          if (step <= 2 && typeof window !== 'undefined') {
            window.history.replaceState({}, '', '/dashboard/create')
          }
          setStep(step - 1)
        } : undefined}
      />

      <main className="px-4 sm:px-6 lg:px-8 pt-6">

        {step === 1 && (
          <div className="space-y-6 animate-in fade-in slide-in-from-bottom-4 duration-500">
            <div className="flex flex-col gap-6">
              <ResumeTypeSelector selectedType={resumeType} onChange={(type) => {
                setResumeType(type)
                // Automatically switch to the correct default template for the mode
                if (type === 'c2c' && !selectedTemplateId.startsWith('c2c')) setSelectedTemplateId('c2c')
                else if (type === 'fulltime' && selectedTemplateId.startsWith('c2c')) setSelectedTemplateId('modern')
              }} />
              <TemplateSelector
                selectedId={selectedTemplateId}
                onChange={setSelectedTemplateId}
                isSubscribed={isPremiumPlan(profileData?.plan_id)}
                onRequiresUpgrade={() => openModal('paywall-modal')}
                resumeType={resumeType}
                profileData={profileData}
              />
              <ResumeDetailsTabs
                profile={profileData}
                editingTab={editingTab}
                onEdit={(tab) => setEditingTab(tab)}
                onCancelEdit={() => setEditingTab(null)}
                renderEditForm={renderEditForm}
              />
            </div>

            <div className="flex justify-end pt-3">
              <Button
                onClick={handleProceedToStep2}
                className="relative h-13 px-8 text-[15px] font-black rounded-2xl bg-[#0F2744] hover:bg-[#0A1C33] text-white shadow-lg shadow-slate-900/15 flex items-center gap-3 transition-all duration-200 hover:-translate-y-0.5 overflow-hidden group/btn cursor-pointer"
              >
                <span className="relative z-10 tracking-wide">Next Step: Target Job &amp; AI Generation</span>
                <ArrowRight className="w-5 h-5 text-[#F59E0B] group-hover/btn:translate-x-1 transition-transform relative z-10" />
              </Button>
            </div>
          </div>
        )}

        {step === 2 && (
          <div className="space-y-6 animate-in fade-in slide-in-from-bottom-4 duration-500">
            {!generatedResume ? (
              <>
                <div className="grid grid-cols-1 lg:grid-cols-2 gap-6 items-start">
                  <div className="w-full min-w-0 space-y-6 relative">
                    {isGenerating && (
                      <AIGenerationLoadingHUD currentState={orchestratorState} />
                    )}
                    <CompanyDetailsSection onGenerate={(company, role, jd) => handleGenerate(company, role, jd)} />
                  </div>

                  <div className="w-full min-w-0 space-y-6">
                    <CreateResumeSidebar />
                  </div>
                </div>
              </>
            ) : (
              <div className="space-y-6">
                {/* Step 2 Top Action & Control Header */}
                <div className="bg-white/95 backdrop-blur-md border border-slate-200/90 rounded-2xl p-4 sm:p-5 flex flex-col md:flex-row items-center justify-between gap-4 shadow-xs">
                  <div className="flex flex-wrap items-center gap-3">
                    <Button
                      onClick={() => {
                        setGeneratedResume(null)
                        if (typeof window !== 'undefined') {
                          window.history.replaceState({}, '', '/dashboard/create')
                        }
                      }}
                      variant="outline"
                      className="h-10 px-4 rounded-xl border-slate-200 text-slate-700 bg-white hover:bg-[#F8FAFC] hover:text-[#0F2744] text-[13px] font-bold flex items-center gap-2 cursor-pointer"
                    >
                      <ArrowLeft className="w-4 h-4" />
                      <span>Edit Target Job &amp; Details</span>
                    </Button>

                    <div className="flex items-center gap-2">
                      <span className="px-3 py-1 rounded-full text-[11.5px] font-extrabold bg-[#EEF4FA] text-[#0F2744] border border-slate-200/80">
                        {getTemplateById(selectedTemplateId).name} Layout
                      </span>
                      <span className={resumeType === 'c2c'
                        ? 'px-3 py-1 rounded-full text-[11.5px] font-extrabold bg-[#FEF3C7] text-[#B45309] border border-[#F59E0B]/30'
                        : 'px-3 py-1 rounded-full text-[11.5px] font-extrabold bg-slate-100 text-slate-700 border border-slate-200'
                      }>
                        {resumeType === 'c2c' ? 'C2C Vendor Submission' : 'Full-Time Corporate'}
                      </span>
                    </div>
                  </div>

                  <div className="flex items-center gap-2 flex-wrap w-full md:w-auto justify-end">
                    <Button
                      onClick={() => setIsRegenerateSummaryModalOpen(true)}
                      variant="outline"
                      className="h-10 px-3.5 rounded-xl border-slate-200 text-slate-700 bg-white hover:bg-[#F8FAFC] hover:text-[#0F2744] text-[12px] font-bold cursor-pointer"
                    >
                      Refine Summary
                    </Button>
                    <Button
                      onClick={() => setIsManualEditModalOpen(true)}
                      variant="outline"
                      className="h-10 px-3.5 rounded-xl border-slate-200 text-slate-700 bg-white hover:bg-[#F8FAFC] hover:text-[#0F2744] text-[12px] font-bold cursor-pointer"
                    >
                      Edit Skills
                    </Button>

                    <Button
                      onClick={handlePrint}
                      className="h-10 px-4 rounded-xl bg-[#0F2744] hover:bg-[#0A1C33] text-white shadow-sm text-[13px] font-extrabold cursor-pointer flex items-center gap-2 transition-all"
                    >
                      <Download className="w-4 h-4 text-[#F59E0B]" />
                      <span>Download PDF</span>
                    </Button>
                    <Button
                      onClick={handleDownloadDocx}
                      disabled={isExportingDocx}
                      variant="outline"
                      className="h-10 px-3.5 rounded-xl border-[#0F2744]/20 text-[#0F2744] bg-[#EEF4FA]/60 hover:bg-[#EEF4FA] text-[12.5px] font-bold flex items-center gap-1.5 cursor-pointer"
                    >
                      {isExportingDocx ? <Loader2 className="w-4 h-4 animate-spin text-[#0F2744]" /> : <FileText className="w-4 h-4 text-[#0F2744]" />}
                      <span>Word (.docx)</span>
                    </Button>
                  </div>
                </div>

                {/* DUAL-COLUMN INTERACTIVE WORKBENCH GRID */}
                <div className="grid grid-cols-1 xl:grid-cols-12 gap-6 xl:gap-8 items-start">

                  {/* LEFT COLUMN: FULL BOLD ATS SCORE METER DASHBOARD (Col-span-5 on xl+) */}
                  <div className="w-full xl:col-span-5 space-y-6">
                    <ATSScoreMeter atsData={atsData} variant="full" />
                  </div>

                  {/* RIGHT COLUMN: HD LIVE PRINTABLE A4 RESUME CANVAS (Col-span-7 on xl+) */}
                  <div className="w-full xl:col-span-7 space-y-4">
                    <div className="bg-white border border-slate-200/90 rounded-2xl p-3 px-4 flex items-center justify-between shadow-2xs">
                      <div className="flex items-center gap-2">
                        <FileText className="w-4 h-4 text-[#0F2744]" />
                        <span className="text-[13px] font-extrabold text-slate-900">Live Resume Canvas</span>
                      </div>

                      {/* Zoom Controls */}
                      <div className="flex items-center gap-1 bg-[#F8FAFC] p-1 rounded-xl border border-slate-200">
                        <button
                          onClick={() => setResumeZoom(z => Math.max(Number((z - 0.1).toFixed(1)), 0.5))}
                          className="p-1 hover:bg-white rounded-lg text-slate-600 hover:text-slate-900 transition-all cursor-pointer"
                          title="Zoom Out"
                        >
                          <ZoomOut className="w-3.5 h-3.5" />
                        </button>
                        <button
                          onClick={() => setResumeZoom(1)}
                          className="px-2 py-0.5 text-[11px] font-bold text-slate-700 hover:text-slate-900 transition-colors cursor-pointer tabular-nums"
                          title="Reset to Fit Width"
                        >
                          {resumeZoom === 1 ? 'Fit Width' : `${Math.round(resumeZoom * 100)}%`}
                        </button>
                        <button
                          onClick={() => setResumeZoom(z => Math.min(Number((z + 0.1).toFixed(1)), 1.5))}
                          className="p-1 hover:bg-white rounded-lg text-slate-600 hover:text-slate-900 transition-all cursor-pointer"
                          title="Zoom In"
                        >
                          <ZoomIn className="w-3.5 h-3.5" />
                        </button>
                      </div>
                    </div>

                    {/* Document Sheet Container */}
                    <div
                      ref={canvasContainerRef}
                      className="bg-slate-200/75 p-3 sm:p-6 rounded-3xl border border-slate-300/80 flex flex-col items-center justify-start overflow-y-auto overflow-x-auto h-[75vh] min-h-[480px] max-h-[860px] shadow-inner scrollbar-thin"
                    >
                      {(() => {
                        const effectiveScale = Number((autoScale * resumeZoom).toFixed(2))
                        return (
                          <div className="flex justify-center transition-all duration-200 py-2 w-full">
                            <div
                              style={{
                                zoom: effectiveScale,
                                width: '794px',
                              }}
                            >
                              {(() => {
                                const SelectedTemplate = getTemplateById(selectedTemplateId).component
                                return <SelectedTemplate resumeData={generatedResume} profileData={profileData} />
                              })()}
                            </div>
                          </div>
                        )
                      })()}
                    </div>

                    {/* Proceed to Step 3 Callout Card */}
                    <div className="relative bg-[#0F2744] overflow-hidden text-white rounded-3xl p-6 flex flex-col sm:flex-row items-center justify-between gap-5 shadow-xl border border-[#1E3A5F] group/card transition-all duration-300">

                      {/* Soft Amber Radial Glow */}
                      <div
                        className="pointer-events-none absolute -top-16 -right-16 w-64 h-64 rounded-full opacity-20"
                        style={{ background: 'radial-gradient(circle, #F59E0B 0%, transparent 70%)' }}
                      />

                      <div className="flex items-center gap-4 relative z-10">
                        <div className="w-12 h-12 rounded-2xl bg-white/10 border border-white/15 flex items-center justify-center text-[#F59E0B] shrink-0">
                          <Sparkles className="w-6 h-6" />
                        </div>
                        <div>
                          <h4 className="text-[16.5px] font-black text-white tracking-tight">
                            Ready for Interview Strategy &amp; Cover Letter?
                          </h4>
                          <p className="text-[13px] font-medium text-slate-300 mt-1">
                            Generate tailored Cover Letter, STAR Stories, Tech Q&amp;A, and Company Notes.
                          </p>
                        </div>
                      </div>

                      <Button
                        onClick={() => setStep(3)}
                        className="relative w-full sm:w-auto h-12 px-7 rounded-2xl bg-[#F59E0B] hover:bg-[#D97706] text-[#0F2744] font-black shadow-lg shadow-amber-500/20 text-[14px] cursor-pointer flex items-center justify-center gap-2.5 shrink-0 group/btn hover:-translate-y-0.5 transition-all duration-200"
                      >
                        <span className="tracking-wide">Proceed to Step 3</span>
                        <ArrowRight className="w-4 h-4 group-hover/btn:translate-x-1 transition-transform" />
                      </Button>
                    </div>
                  </div>

                </div>
              </div>
            )}
          </div>
        )}

        {step === 3 && (
          <div className="space-y-6 animate-in fade-in slide-in-from-bottom-4 duration-500">
            {/* Top Navigation Bar */}
            <div className="flex flex-col lg:flex-row lg:items-center justify-between gap-4 bg-white/95 backdrop-blur-md p-4 sm:p-5 rounded-2xl border border-slate-200/90 shadow-xs">
              <div className="flex flex-wrap items-center gap-3">
                <Button
                  onClick={() => setStep(2)}
                  className="h-9 px-4 rounded-xl text-slate-700 hover:text-[#0F2744] hover:bg-[#F8FAFC] bg-white border border-slate-200 cursor-pointer"
                >
                  <div className="flex items-center gap-1.5 text-[13px] font-bold">
                    <ArrowLeft className="w-3.5 h-3.5" />
                    Back to Resume Preview
                  </div>
                </Button>

                {/* Real-time ATS Score Meter Pill */}
                <ATSScoreMeter atsData={atsData} variant="compact" />
              </div>

              <div className="flex items-center gap-2">
                <span className="text-[13.5px] font-extrabold text-slate-900 hidden md:inline">
                  Step 3 of 3: Interview &amp; Application Strategy Workspace
                </span>
              </div>

              <div className="flex flex-wrap items-center gap-2">
                <Button onClick={handlePrint} className="h-9 px-4 rounded-xl bg-[#0F2744] hover:bg-[#0A1C33] text-white shadow-xs text-[13px] font-bold cursor-pointer flex items-center gap-1.5">
                  <Download className="w-4 h-4 text-[#F59E0B]" />
                  Download PDF
                </Button>
                <Button 
                  onClick={handleDownloadDocx} 
                  disabled={isExportingDocx}
                  variant="outline" 
                  className="h-9 px-4 rounded-xl border-[#0F2744]/20 text-[#0F2744] bg-[#EEF4FA]/60 hover:bg-[#EEF4FA] text-[13px] font-bold cursor-pointer flex items-center gap-1.5"
                >
                  {isExportingDocx ? <Loader2 className="w-4 h-4 animate-spin text-[#0F2744]" /> : <FileText className="w-4 h-4 text-[#0F2744]" />}
                  <span>Word (.docx)</span>
                </Button>
              </div>
            </div>

            {/* Dedicated Full-Width Interview & Application Strategy Workspace */}
            <div className="w-full">
              <WorkspaceSection
                interviewPrep={interviewPrep}
                atsData={atsData}
                resumeId={currentResumeId}
                candidateName={profileData?.full_name}
                email={profileData?.email}
                phone={profileData?.phone}
                location={profileData?.location}
                linkedin={profileData?.linkedin}
                companyName={profileData?.parsedJd?.company_name || profileData?.company_name}
                jobTitle={profileData?.parsedJd?.job_title || profileData?.job_title}
                parsedJdData={savedParsedJdData || profileData?.parsedJd}
                generatedResume={generatedResume}
                onPrepRegenerated={(newPrep) => setInterviewPrep(newPrep)}
              />
            </div>
          </div>
        )}

        {/* Modals for Step 3 fallbacks */}
        <RegenerateSummaryModal
          isOpen={isRegenerateSummaryModalOpen}
          onClose={() => setIsRegenerateSummaryModalOpen(false)}
          onRegenerate={handleRegenerateSummary}
        />
        <ManualEditModal
          isOpen={isManualEditModalOpen}
          onClose={() => setIsManualEditModalOpen(false)}
          onSave={handleManualEditSave}
          initialSkills={generatedResume?.skills || []}
        />

        {/* Empty Profile Guard Modal */}
        {isEmptyProfileModalOpen && (
          <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/60 backdrop-blur-xs animate-in fade-in duration-200">
            <div className="bg-white rounded-3xl max-w-lg w-full p-6 sm:p-8 shadow-2xl border border-slate-200/90 space-y-6 relative animate-in zoom-in-95 duration-200">
              <div className="flex items-start gap-4">
                <div className="w-12 h-12 rounded-2xl bg-[#FEF3C7] border border-[#F59E0B]/30 flex items-center justify-center text-[#D97706] shrink-0">
                  <AlertTriangle className="w-6 h-6" />
                </div>
                <div>
                  <h3 className="text-[19px] font-black text-slate-900 tracking-tight">
                    Work Experience Missing
                  </h3>
                  <p className="text-[13px] font-medium text-slate-500 mt-1 leading-relaxed">
                    Our Enterprise AI strictly adheres to your real career history and <span className="font-bold text-slate-700">never fabricates fake companies</span>. 
                    Generating now without work experience will produce an empty work history.
                  </p>
                </div>
              </div>

              <div className="p-4 rounded-2xl bg-[#F8FAFC] border border-slate-200/80 space-y-2 text-[13px]">
                <div className="font-bold text-slate-800 flex items-center gap-2">
                  <Sparkles className="w-4 h-4 text-[#D97706]" />
                  Fastest Way (Takes 10 Seconds):
                </div>
                <p className="text-slate-600 leading-normal">
                  Export your LinkedIn profile using <b>&quot;Save to PDF&quot;</b> and import it in your <b>Master Profile</b>. All your roles, education, and skills will be auto-filled instantly!
                </p>
              </div>

              <div className="flex flex-col sm:flex-row items-center gap-3 pt-2">
                <Button
                  onClick={() => {
                    setIsEmptyProfileModalOpen(false)
                    router.push('/dashboard/profile')
                  }}
                  className="w-full sm:flex-1 h-12 rounded-xl bg-[#0F2744] hover:bg-[#0A1C33] text-white font-bold text-[14px] shadow-md cursor-pointer flex items-center justify-center gap-2"
                >
                  <span>Go to Master Profile</span>
                  <ArrowRight className="w-4 h-4 text-[#F59E0B]" />
                </Button>

                <Button
                  onClick={() => {
                    setIsEmptyProfileModalOpen(false)
                    setEditingTab('employment')
                  }}
                  variant="outline"
                  className="w-full sm:w-auto h-12 px-5 rounded-xl border-slate-200 text-slate-700 hover:bg-[#F8FAFC] font-bold text-[14px] cursor-pointer"
                >
                  Add Job Below
                </Button>
              </div>

              <div className="text-center pt-1">
                <button
                  onClick={() => {
                    setIsEmptyProfileModalOpen(false)
                    setStep(2)
                  }}
                  className="text-[12px] font-semibold text-slate-400 hover:text-slate-600 underline cursor-pointer transition-colors"
                >
                  Proceed anyway without work experience
                </button>
              </div>
            </div>
          </div>
        )}

        {/* Dedicated Always-Mounted Print Target for 100% Reliable PDF Download across Steps 2 & 3 */}
        {generatedResume && (
          <div
            aria-hidden="true"
            style={{
              position: 'absolute',
              left: '-99999px',
              top: 0,
              width: '794px',
              opacity: 0,
              pointerEvents: 'none',
              zIndex: -9999
            }}
          >
            {(() => {
              const PrintTemplate = getTemplateById(selectedTemplateId).component
              return (
                <div ref={resumeRef}>
                  <PrintTemplate
                    resumeData={generatedResume}
                    profileData={profileData}
                  />
                </div>
              )
            })()}
          </div>
        )}
      </main>
    </div>
  )
}
